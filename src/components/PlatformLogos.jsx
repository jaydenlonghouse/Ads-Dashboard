/** @param {{ platforms: ('google'|'meta')[] }} props */
export function DealPlatformIcons({ platforms }) {
  const showGoogle = platforms.includes('google')
  const showMeta = platforms.includes('meta')
  if (!showGoogle && !showMeta) return null

  return (
    <span className="inline-flex shrink-0 items-center gap-0.5" aria-hidden>
      {showGoogle ? <GoogleLogo className="h-4 w-4" /> : null}
      {showMeta ? <MetaLogo className="h-4 w-4" /> : null}
    </span>
  )
}
